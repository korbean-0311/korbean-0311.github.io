function escRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

// -- Helpers --------------------------------------------------------------
function readJSON(name) {
  return JSON.parse(fs.readFileSync(path.join(DATA_DIR, name), 'utf8'));
}

// Escape plain-text JSON values destined for HTML text nodes/attributes.
function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// Some fields contain author-approved inline markup we must preserve:
//   - news.body            → authored HTML (e.g. <strong>)
//   - research summaries   → contain <u>…</u>
// For those we escape everything EXCEPT the small whitelist of tags the site
// itself emits, mirroring the client renderers.
function richInline(s) {
  return esc(s)
    .replace(/&lt;(\/?(?:strong|em|u|br\s*\/?))&gt;/gi, '<$1>');
}

// education note tokens: {{name}} → link (if note_link) or plain text.
function renderNote(note, link) {
  if (!note) return '';
  const safe = esc(note);
  if (!link) return safe.replace(/\{\{(.+?)\}\}/g, '$1');
  return safe.replace(/\{\{(.+?)\}\}/g, (_, name) =>
    `<a href="${esc(link)}" target="_blank" rel="noopener">${name}</a>`);
}

// Wrap the author's own name so a crawler can spot the page owner at a glance.
function highlightAuthor(authors, me) {
  const safe = esc(authors || '');
  if (!me) return safe;
  const safeMe = esc(me).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return safe.replace(new RegExp(safeMe, 'g'), m => `<strong>${m}</strong>`);
}

// -- Per-item formatters --------------------------------------------------
function pubLi(p) {
  const num = p.number != null ? `[${esc(p.number)}] ` : '';
  const rows = [];
  rows.push(`<strong>${num}${esc(p.title)}</strong>`);
  if (p.authors) rows.push(`Authors: ${highlightAuthor(p.authors, p.highlight_author)}`);
  if (p.venue) rows.push(`Venue: ${esc(p.venue)}`);
  if (p.details) rows.push(`Details: ${esc(p.details)}`);
  if (p.doi) rows.push(`DOI: <a href="${esc(p.doi)}" target="_blank" rel="noopener">${esc(p.doi)}</a>`);
  if (p.pdf) rows.push(`PDF: <a href="${esc(p.pdf)}">${esc(p.pdf)}</a>`);
  if (Array.isArray(p.tags) && p.tags.length) rows.push(`Tags: ${esc(p.tags.join(', '))}`);
  const noteLabels = (p.notes || [])
    .map(n => (typeof n === 'string' ? n : (n && n.label) || ''))
    .filter(Boolean);
  if (noteLabels.length) rows.push(`Notes: ${esc(noteLabels.join('; '))}`);
  if (Array.isArray(p.keywords) && p.keywords.length) rows.push(`Keywords: ${esc(p.keywords.join(', '))}`);
  if (p.abstract && p.abstract.trim()) rows.push(`Abstract: ${esc(p.abstract)}`);
  let html = `<li>${rows.join('<br />\n')}`;
  if (p.bibtex && p.bibtex.trim()) {
    html += `\n<pre>${esc(p.bibtex)}</pre>`;
  }
  html += `</li>`;
  return html;
}

function patentLi(p) {
  const rows = [`<strong>[${esc(p.number)}] ${esc(p.title)}</strong>${p.country ? ` (${esc(p.country)})` : ''}`];
  if (p.inventors) rows.push(`Inventors: ${highlightAuthor(p.inventors, p.highlight_author)}`);
  if (p.patent_no) rows.push(`Patent No.: ${esc(p.patent_no)}`);
  if (p.granted_date) rows.push(`Granted date: ${esc(p.granted_date)}`);
  return `<li>${rows.join('<br />\n')}</li>`;
}

function awardLi(a) {
  const parts = [];
  if (a.venue) parts.push(`<em>${esc(a.venue)}</em>`);
  if (a.title) parts.push(`<strong>${esc(a.title)}</strong>`);
  let line = parts.join(', ');
  if (a.highlight) line += ` <em>(${esc(a.highlight)})</em>`;
  if (a.date) line += `, ${esc(a.date)}`;
  if (Array.isArray(a.tags) && a.tags.length) line += ` [${esc(a.tags.join(', '))}]`;
  return `<li>${line}.</li>`;
}

// -- Per-page builders ----------------------------------------------------
function buildNews() {
  const data = readJSON('news.json');
  const news = Array.isArray(data) ? data : (data?.news || []);
  const items = news.map(n => {
    const tag = n.tag ? ` <em>(${esc(n.tag)})</em>` : '';
    return `    <li><strong>${esc(n.date)}</strong> — ${richInline(n.body)}${tag}</li>`;
  }).join('\n');
  return `<section aria-label="Recent news (text fallback for non-JavaScript clients)">
  <h2>Recent News</h2>
  <ul>
${items}
  </ul>
</section>`;
}

function buildPublications() {
  const pubs = readJSON('publications.json');
  const out = ['<h2>Publications &amp; Awards</h2>'];

  const group = (title, items, fmt) => {
    if (!items || !items.length) return;
    out.push(`<section>\n  <h3>${title}</h3>\n  <ul>\n${items.map(fmt).join('\n')}\n  </ul>\n</section>`);
  };

  group('International Journals — Under Review', pubs.international_journals?.under_review, pubLi);
  group('International Journals — Published', pubs.international_journals?.published, pubLi);
  group('International Conferences', pubs.international_conferences, pubLi);
  group('Domestic Conferences (KIEES)', pubs.domestic_conferences, pubLi);
  group('Patents', pubs.patents, patentLi);

  // Awards: array-of-groups [{ category, items }], with legacy fallbacks.
  const awards = pubs.awards;
  if (awards) {
    let html = '<section>\n  <h3>Awards</h3>';
    if (Array.isArray(awards) && awards.length && awards[0] && Array.isArray(awards[0].items)) {
      for (const g of awards) {
        html += `\n  <h4>${esc(g.category || '')}</h4>\n  <ul>\n${(g.items || []).map(awardLi).join('\n')}\n  </ul>`;
      }
    } else if (Array.isArray(awards)) {
      html += `\n  <ul>\n${awards.map(awardLi).join('\n')}\n  </ul>`;
    } else {
      for (const [cat, items] of Object.entries(awards)) {
        html += `\n  <h4>${esc(cat)}</h4>\n  <ul>\n${(items || []).map(awardLi).join('\n')}\n  </ul>`;
      }
    }
    html += '\n</section>';
    out.push(html);
  }

  return out.join('\n');
}

function buildEducation() {
  const edu = readJSON('education.json');
  const items = edu.map(e => {
    const rows = [];
    const loc = e.location ? ` <em>(${esc(e.location)})</em>` : '';
    const school = e.school_link
      ? `<a href="${esc(e.school_link)}" target="_blank" rel="noopener">${esc(e.school)}</a>`
      : esc(e.school);
    rows.push(`<strong>${esc(e.period)}</strong> — ${school}${loc}`);
    if (e.degree) rows.push(esc(e.degree));
    for (const a of e.advisors || []) {
      const name = a.link
        ? `<a href="${esc(a.link)}" target="_blank" rel="noopener">${esc(a.name)}</a>`
        : esc(a.name);
      const note = a.note ? ` (${renderNote(a.note, a.note_link)})` : '';
      rows.push(`${esc(a.label)}: ${name}${note}`);
    }
    return `    <li>${rows.join('<br />\n')}</li>`;
  }).join('\n');
  return `<h2>Education</h2>\n<ul>\n${items}\n</ul>`;
}

function buildResearch() {
  const res = readJSON('research.json');
  const out = ['<h2>Research</h2>'];
  for (const sec of res.sections || []) {
    out.push(`<section>\n  <h3>${esc(sec.title)}</h3>`);
    if (sec.affiliation) {
      const labs = (sec.affiliation.labs || [])
        .map(l => `<strong>${esc(l.name)}</strong>${l.pi ? ` (PI: ${esc(l.pi)})` : ''}`)
        .join(' &amp; ');
      const inst = sec.affiliation.institution ? ` at ${esc(sec.affiliation.institution)}` : '';
      const note = sec.affiliation.note ? ` (${esc(sec.affiliation.note)})` : '';
      out.push(`  <p><em>Affiliation:</em> ${labs}${inst}${note}</p>`);
    }
    if (sec.type === 'graduate') {
      for (const p of sec.projects || []) {
        const rows = [`<strong>[${esc(p.code)}] ${esc(p.title)}</strong>`];
        if (p.org) rows.push(`Organization: ${esc(p.org)}`);
        if (p.period) rows.push(`Period: ${esc(p.period)}`);
        if (Array.isArray(p.keywords) && p.keywords.length) rows.push(`Keywords: ${esc(p.keywords.join(', '))}`);
        let block = `  <article>\n    <p>${rows.join('<br />\n')}</p>`;
        if (Array.isArray(p.summary) && p.summary.length) {
          block += `\n    <ul>\n${p.summary.map(s => `      <li>${richInline(s)}</li>`).join('\n')}\n    </ul>`;
        }
        block += `\n  </article>`;
        out.push(block);
      }
    } else if (sec.type === 'undergraduate') {
      for (const g of sec.groups || []) {
        const head = `<strong>${esc(g.lab)}</strong>${g.advisor ? ` (Advisor: ${esc(g.advisor)})` : ''}${g.institution ? `, at ${esc(g.institution)}` : ''}${g.period ? ` (${esc(g.period)})` : ''}`;
        let block = `  <article>\n    <p>${head}</p>`;
        if (Array.isArray(g.items) && g.items.length) {
          block += `\n    <ul>\n${g.items.map(it => `      <li>${richInline(it)}</li>`).join('\n')}\n    </ul>`;
        }
        block += `\n  </article>`;
        out.push(block);
      }
    }
    out.push('</section>');
  }
  return out.join('\n');
}

function buildOthers() {
  const others = readJSON('others.json');
  const out = ['<h2>Others</h2>'];

  const reviewer = (others.reviewer || []).map(it =>
    `    <li><em>${esc(it.name)}</em>${it.year ? `, ${esc(it.year)}` : ''}.</li>`).join('\n');
  out.push(`<section>\n  <h3>Reviewer Activities</h3>\n  <ul>\n${reviewer}\n  </ul>\n</section>`);

  const scholarships = (others.scholarships || []).map(it => {
    const det = it.details ? ` ${esc(it.details)}` : '';
    const dt = it.date ? ` (${esc(it.date)})` : '';
    return `    <li><strong>${esc(it.name)}</strong>,${det}${dt}</li>`;
  }).join('\n');
  out.push(`<section>\n  <h3>Scholarships</h3>\n  <ul>\n${scholarships}\n  </ul>\n</section>`);

  const ta = (others.ta || []).map(it => {
    const code = it.code ? ` (${esc(it.code)})` : '';
    const inst = it.institution ? `, ${esc(it.institution)}` : '';
    const term = it.term ? `, ${esc(it.term)}` : '';
    return `    <li>${esc(it.course)}${code}${inst}${term}</li>`;
  }).join('\n');
  out.push(`<section>\n  <h3>Undergraduate Class TA</h3>\n  <ul>\n${ta}\n  </ul>\n</section>`);

  let cw = '<section>\n  <h3>Selected Coursework</h3>';
  for (const g of others.coursework || []) {
    const courses = (g.courses || []).map(c => {
      if (typeof c === 'string') return `    <li>${esc(c)}</li>`;
      const note = c.note ? ` <em>(${esc(c.note)})</em>` : '';
      return `    <li>${esc(c.name)}${note}</li>`;
    }).join('\n');
    cw += `\n  <h4>${esc(g.school)}</h4>\n  <ul>\n${courses}\n  </ul>`;
  }
  cw += '\n</section>';
  out.push(cw);

  let prog = '<section>\n  <h3>Programming Skills</h3>';
  for (const cat of others.programming || []) {
    prog += `\n  <h4>${esc(cat.category)}</h4>`;
    if (Array.isArray(cat.skills) && cat.skills.length) {
      prog += `\n  <ul>\n${cat.skills.map(s => `    <li>${esc(s.name)} (${esc(s.level)}/5)</li>`).join('\n')}\n  </ul>`;
    } else if (Array.isArray(cat.subgroups) && cat.subgroups.length) {
      for (const sg of cat.subgroups) {
        if (Array.isArray(sg.skills) && sg.skills.length) {
          prog += `\n  <p><em>${esc(sg.label)}</em></p>\n  <ul>\n${sg.skills.map(s => `    <li>${esc(s.name)} (${esc(s.level)}/5)</li>`).join('\n')}\n  </ul>`;
        } else if (Array.isArray(sg.items) && sg.items.length) {
          prog += `\n  <p><em>${esc(sg.label)}</em></p>\n  <ul>\n${sg.items.map(i => `    <li>${esc(i)}</li>`).join('\n')}\n  </ul>`;
        }
      }
    } else if (Array.isArray(cat.items) && cat.items.length) {
      prog += `\n  <ul>\n${cat.items.map(i => `    <li>${esc(i)}</li>`).join('\n')}\n  </ul>`;
    }
  }
  prog += '\n</section>';
  out.push(prog);

  return out.join('\n');
}

// -- JSON-LD (schema.org) -------------------------------------------------
// Canonical identity of the site owner, so every article links to one entity.
const OWNER_ID = 'https://orcid.org/0000-0003-3342-3707';
const OWNER_NAMES = new Set(['Y.-S. Lee', 'Young-Seok Lee', 'Youngseok Lee', 'Y. Lee']);

// Split an author string ("Y.-S. Lee, T. Yoon, and S. Nam*") into clean names.
// The owner's own entries get the ORCID @id so the graph reconciles them.
function parseAuthors(s) {
  return String(s || '')
    .split(/,|\band\b/)
    .map(a => a.replace(/\*/g, '').trim())
    .filter(Boolean)
    .map(name => OWNER_NAMES.has(name)
      ? { '@type': 'Person', '@id': OWNER_ID, name }
      : { '@type': 'Person', name });
}

function extractYear(...fields) {
  for (const f of fields) {
    const m = String(f || '').match(/\b(19|20)\d{2}\b/);
    if (m) return m[0];
  }
  return null;
}

function scholarlyArticle(p) {
  const node = { '@type': 'ScholarlyArticle', name: p.title, headline: p.title };
  const authors = parseAuthors(p.authors);
  if (authors.length) node.author = authors;
  if (p.venue) node.isPartOf = { '@type': 'Periodical', name: p.venue };
  const year = extractYear(p.details);
  if (year) node.datePublished = year;
  if (p.abstract && p.abstract.trim()) node.abstract = p.abstract;
  if (Array.isArray(p.keywords) && p.keywords.length) node.keywords = p.keywords.join(', ');
  if (p.doi) { node.sameAs = p.doi; node.url = p.doi; }
  return node;
}

// One @graph of every journal + conference article, generated from
// publications.json so it stays in sync with the rendered list.
function buildPublicationsJsonLd() {
  const pubs = readJSON('publications.json');
  const articles = [
    ...(pubs.international_journals?.under_review || []),
    ...(pubs.international_journals?.published || []),
    ...(pubs.international_conferences || []),
    ...(pubs.domestic_conferences || []),
  ].map(scholarlyArticle);

  const author = {
    '@type': 'Person',
    '@id': OWNER_ID,
    name: 'Young-Seok Lee',
    url: 'https://korbean-0311.github.io/',
    identifier: {
      '@type': 'PropertyValue',
      propertyID: 'ORCID',
      value: '0000-0003-3342-3707',
      url: OWNER_ID,
    },
    sameAs: [
      OWNER_ID,
      'https://scholar.google.com/citations?user=yCXRScIAAAAJ&hl=en',
    ],
  };
  // The owner node defines the ORCID entity once; each article's author list
  // references it by the same @id, so consumers merge them into one identity.
  const graph = {
    '@context': 'https://schema.org',
    '@graph': [author, ...articles],
  };

  // Minified (no pretty-print) to keep the page light; escape '<' so a stray
  // sequence can never close the <script> early.
  const json = JSON.stringify(graph).replace(/</g, '\\u003c');
  return `<script type="application/ld+json">${json}</script>`;
}

// -- Static-first page content (same markup the browser JS used to render) --
// Rendering now happens here at build time and is baked into the visible HTML,
// so there is no JSON fetch, no "Loading…" flash, and no hidden fallback. The
// browser JS only enhances (tabs, sort, copy, show-more).
const ARROW_SVG = '<svg class="ext-link-arrow" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 17L17 7"/><path d="M9 7h8v8"/></svg>';

function eduRenderNote(note, link) {
  if (!note) return '';
  const safe = esc(note);
  if (!link) return safe.replace(/\{\{(.+?)\}\}/g, '$1');
  return safe.replace(/\{\{(.+?)\}\}/g, (_, name) =>
    `<a href="${esc(link)}" target="_blank" rel="noopener">${name}${ARROW_SVG}</a>`);
}

function renderEducationTimeline() {
  const edu = readJSON('education.json');
  return edu.map(item => {
    const advisorRows = (item.advisors || []).map(a => {
      const nameLink = a.link
        ? `<a href="${esc(a.link)}" target="_blank" rel="noopener">${esc(a.name)}${ARROW_SVG}</a>`
        : esc(a.name);
      const noteHTML = a.note ? ` (${eduRenderNote(a.note, a.note_link)})` : '';
      return `<div class="timeline-card__advisor"><span class="adv-label">${esc(a.label)}:</span> ${nameLink}${noteHTML}</div>`;
    }).join('');
    const degreeHTML = item.degree
      ? esc(item.degree).replace(/(Electrical and Computer Engineering|Electrical Engineering)/, '<em>$1</em>')
      : '';
    const locationHTML = item.location
      ? `<span class="timeline-card__loc">(${esc(item.location)})</span>`
      : '';
    const schoolHTML = item.school_link
      ? `<a href="${esc(item.school_link)}" target="_blank" rel="noopener">${esc(item.school)}${ARROW_SVG}</a>`
      : esc(item.school);
    return `        <li class="timeline-item">
          <div class="timeline-card">
            <div class="timeline-card__period">${esc(item.period)}</div>
            <div class="timeline-card__school">${schoolHTML} ${locationHTML}</div>
            ${degreeHTML ? `<div class="timeline-card__degree">${degreeHTML}</div>` : ''}
            ${advisorRows}
          </div>
        </li>`;
  }).join('\n');
}

// Replace the inner content between <!-- R:key:START --> / <!-- R:key:END -->.
function injectRegion(html, key, content) {
  const s = `<!-- R:${key}:START -->`, e = `<!-- R:${key}:END -->`;
  const re = new RegExp(escRe(s) + '[\\s\\S]*?' + escRe(e));
  if (!re.test(html)) throw new Error(`region "${key}" markers not found`);
  return html.replace(re, `${s}\n${content}\n      ${e}`);
}

