// Replace the content between `start`/`end` markers, or — if absent — insert
// `block` just before the last occurrence of `anchor` (e.g. </main>, </head>).
function replaceMarked(html, start, end, block, anchor) {
  const re = new RegExp(escRe(start) + '[\\s\\S]*?' + escRe(end));
  if (re.test(html)) return html.replace(re, block);
  const idx = html.lastIndexOf(anchor);
  if (idx === -1) throw new Error(`anchor ${anchor} not found and no markers present.`);
  return html.slice(0, idx) + block + '\n  ' + html.slice(idx);
}

function main() {
  // 1) Static-first pages: render the real content straight into visible regions.
  for (const [file, regions] of Object.entries(STATIC_PAGES)) {
    const filePath = path.join(ROOT, file);
    let html = fs.readFileSync(filePath, 'utf8');
    for (const [key, render] of regions) {
      html = injectRegion(html, key, render());
    }
    fs.writeFileSync(filePath, html, 'utf8');
    console.log(`Rendered static content into ${file} (${regions.map(r => r[0]).join(', ')})`);
  }

  // 2) ScholarlyArticle JSON-LD in <head> of the page that lists the papers.
  {
    const filePath = path.join(ROOT, 'academics.html');
    let html = fs.readFileSync(filePath, 'utf8');
    const ld = buildPublicationsJsonLd();
    const block = `${JSONLD_START}\n  `
      + ld.split('\n').map(l => (l ? '  ' + l : l)).join('\n') + '\n'
      + `  ${JSONLD_END}`;
    html = replaceMarked(html, JSONLD_START, JSONLD_END, block, '</head>');
    fs.writeFileSync(filePath, html, 'utf8');
    console.log(`Injected publications JSON-LD into academics.html (${block.length} bytes)`);
  }

  // 3) Shared profile sidebar in the left column of every page (academics.html
  //    additionally gets the "On this page" section index), and cache-busting
  //    stamps on the stylesheet / scripts.
  {
    const pages = [['index.html', {}], ['academics.html', { withIndex: true }], ['contact.html', {}]];
    for (const [file, opts] of pages) {
      const filePath = path.join(ROOT, file);
      let html = fs.readFileSync(filePath, 'utf8');
      if (!new RegExp(escRe(PROFILE_START)).test(html)) {
        console.warn(`  ${file}: no PROFILE markers — skipped`);
        continue;
      }
      const block = `${PROFILE_START}\n    ${buildProfile(opts)}\n    ${PROFILE_END}`;
      html = replaceMarked(html, PROFILE_START, PROFILE_END, block, '</main>');
      html = stampAssets(html);
      fs.writeFileSync(filePath, html, 'utf8');
      console.log(`Injected profile into ${file}`);
    }
  }
}

// -- Cache busting --------------------------------------------------------
// GitHub Pages serves assets with a 10-minute max-age, so a phone that just
// loaded the site keeps the old stylesheet across a redeploy. Each page
// references css/style.css and the scripts with ?v=<content hash>, which
// changes exactly when the file does (idempotent otherwise).
const STAMPED_ASSETS = ['css/style.css', 'js/main.js', 'js/publications.js'];
function assetHash(rel) {
  const file = path.join(ROOT, rel);
  if (!fs.existsSync(file)) return null;
  // Hash with CR stripped: a Windows checkout has CRLF working copies while
  // CI (and the repo) have LF, and the stamp must not differ between them —
  // otherwise every CI run re-stamps and commits.
  const text = fs.readFileSync(file, 'utf8').replace(/\r/g, '');
  return crypto.createHash('sha1').update(text, 'utf8').digest('hex').slice(0, 8);
}
function stampAssets(html) {
  for (const rel of STAMPED_ASSETS) {
    const hash = assetHash(rel);
    if (!hash) continue;
    const re = new RegExp(`((?:href|src)=")${escRe(rel)}(?:\\?v=[0-9a-f]+)?(")`, 'g');
    html = html.replace(re, `$1${rel}?v=${hash}$2`);
  }
  return html;
}

