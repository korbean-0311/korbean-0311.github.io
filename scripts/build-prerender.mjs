#!/usr/bin/env node
/**
 * build-prerender.mjs — Renders each page's JSON-driven content (data/*.json)
 * straight into the visible HTML at build time (static-first), so there is no
 * client-side fetch, no "Loading…" flash, and non-JS crawlers get the full text.
 *
 * WHAT IT DOES
 *   1. STATIC_PAGES: replaces the content between `<!-- R:key:START -->` /
 *      `<!-- R:key:END -->` markers in each page with freshly rendered HTML.
 *      index.html gets news + press; academics.html gets every other section
 *      (education, publications, awards, research, academic service,
 *      coursework) on one long page.
 *   2. Injects the publications JSON-LD (<head>) between the AI-JSONLD markers.
 *   3. Injects the shared profile sidebar between the PROFILE markers (with the
 *      "On this page" section index on academics.html).
 *   The browser JS only enhances (tabs, BibTeX copy, "show more", scroll-spy).
 *
 * IDEMPOTENT
 *   Each region is rewritten between its markers, so re-running is safe.
 *
 * Run locally:   node scripts/build-prerender.mjs
 * Run in CI:     .github/workflows/build-llms.yml
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'data');

const JSONLD_START = '<!-- AI-JSONLD:START (auto-generated by scripts/build-prerender.mjs — do not edit by hand) -->';
const JSONLD_END = '<!-- AI-JSONLD:END -->';
const PROFILE_START = '<!-- PROFILE:START (auto-generated by scripts/build-prerender.mjs — do not edit by hand) -->';
const PROFILE_END = '<!-- PROFILE:END -->';

function escRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

// -- Helpers --------------------------------------------------------------
function readJSON(name) {
  return JSON.parse(fs.readFileSync(path.join(DATA_DIR, name), 'utf8'));
}

// Escape plain-text JSON values destined for HTML text nodes/attributes.
function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// -- JSON-LD (schema.org) -------------------------------------------------
// Canonical identity of the site owner, so every article links to one entity.
const OWNER_ID = 'https://orcid.org/0000-0003-3342-3707';
const OWNER_NAMES = new Set(['Y.-S. Lee', 'Young-Seok Lee', 'Youngseok Lee', 'Y. Lee']);

// Split an author string ("Y.-S. Lee, T. Yoon, and S. Nam*") into clean names.
// The owner's own entries get the ORCID @id so the graph reconciles them.
function parseAuthors(s) {
  return String(s || '')
    .split(/,|\band\b/)
    .map(a => a.replace(/\*/g, '').trim())
    .filter(Boolean)
    .map(name => OWNER_NAMES.has(name)
      ? { '@type': 'Person', '@id': OWNER_ID, name }
      : { '@type': 'Person', name });
}

function extractYear(...fields) {
  for (const f of fields) {
    const m = String(f || '').match(/\b(19|20)\d{2}\b/);
    if (m) return m[0];
  }
  return null;
}

function scholarlyArticle(p) {
  const node = { '@type': 'ScholarlyArticle', name: p.title, headline: p.title };
  const authors = parseAuthors(p.authors);
  if (authors.length) node.author = authors;
  if (p.venue) node.isPartOf = { '@type': 'Periodical', name: p.venue };
  const year = extractYear(p.details);
  if (year) node.datePublished = year;
  if (p.abstract && p.abstract.trim()) node.abstract = p.abstract;
  if (Array.isArray(p.keywords) && p.keywords.length) node.keywords = p.keywords.join(', ');
  if (p.doi) { node.sameAs = p.doi; node.url = p.doi; }
  return node;
}

// One @graph of every journal + conference article, generated from
// publications.json so it stays in sync with the rendered list.
function buildPublicationsJsonLd() {
  const pubs = readJSON('publications.json');
  const articles = [
    ...(pubs.international_journals?.under_review || []),
    ...(pubs.international_journals?.published || []),
    ...(pubs.international_conferences || []),
    ...(pubs.domestic_conferences || []),
  ].map(scholarlyArticle);

  const author = {
    '@type': 'Person',
    '@id': OWNER_ID,
    name: 'Young-Seok Lee',
    url: 'https://korbean-0311.github.io/',
    identifier: {
      '@type': 'PropertyValue',
      propertyID: 'ORCID',
      value: '0000-0003-3342-3707',
      url: OWNER_ID,
    },
    sameAs: [
      OWNER_ID,
      'https://scholar.google.com/citations?user=yCXRScIAAAAJ&hl=en',
    ],
  };
  // The owner node defines the ORCID entity once; each article's author list
  // references it by the same @id, so consumers merge them into one identity.
  const graph = {
    '@context': 'https://schema.org',
    '@graph': [author, ...articles],
  };

  // Minified (no pretty-print) to keep the page light; escape '<' so a stray
  // sequence can never close the <script> early.
  const json = JSON.stringify(graph).replace(/</g, '\\u003c');
  return `<script type="application/ld+json">${json}</script>`;
}

// -- Static-first page content (same markup the browser JS used to render) --
// Rendering now happens here at build time and is baked into the visible HTML,
// so there is no JSON fetch, no "Loading…" flash, and no hidden fallback. The
// browser JS only enhances (tabs, sort, copy, show-more).
const ARROW_SVG = '<svg class="ext-link-arrow" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 17L17 7"/><path d="M9 7h8v8"/></svg>';

function eduRenderNote(note, link) {
  if (!note) return '';
  const safe = esc(note);
  if (!link) return safe.replace(/\{\{(.+?)\}\}/g, '$1');
  return safe.replace(/\{\{(.+?)\}\}/g, (_, name) =>
    `<a href="${esc(link)}" target="_blank" rel="noopener">${name}${ARROW_SVG}</a>`);
}

// Education rows in the reference layout (sehyunryu.github.io): period in a
// left column, then a white logo chip beside the copy; the DEGREE leads as the
// headline, school + pin-location share the next line, advisors sit below in
// muted text. Rows are separated by hairlines — no cards, no timeline spine.
const PIN_SVG = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 10c0 7-9 13-9 13s-9-6-9-13a9 9 0 0 1 18 0z"/><circle cx="12" cy="10" r="3"/></svg>';

function renderEducationTimeline() {
  const edu = readJSON('education.json');
  return edu.map(item => {
    const advisorRows = (item.advisors || []).map(a => {
      const nameLink = a.link
        ? `<a href="${esc(a.link)}" target="_blank" rel="noopener">${esc(a.name)}${ARROW_SVG}</a>`
        : esc(a.name);
      // The advisor's own pedigree goes on its own line (CSS: display:block).
      const noteHTML = a.note ? `<span class="adv-note">(${eduRenderNote(a.note, a.note_link)})</span>` : '';
      return `<div><span class="adv-label">${esc(a.label)}:</span> ${nameLink}${noteHTML}</div>`;
    }).join('\n              ');
    const schoolLink = item.school_link
      ? `<a href="${esc(item.school_link)}" target="_blank" rel="noopener"><strong>${esc(item.school)}</strong>${ARROW_SVG}</a>`
      : `<strong>${esc(item.school)}</strong>`;
    const locHTML = item.location ? `<span class="edu-loc">${PIN_SVG}${esc(item.location)}</span>` : '';
    // Entries without a degree (high school) promote the school into the
    // headline instead of repeating it on the place line.
    const heading = item.degree ? esc(item.degree) : schoolLink;
    const placeInner = item.degree ? `${schoolLink}${locHTML}` : locHTML;
    const logoHTML = item.logo
      ? `<div class="edu-logo"><img src="${esc(item.logo)}" alt="${esc(item.school)} logo" width="72" height="72" loading="lazy" decoding="async" /></div>`
      : '';
    return `        <article class="edu-item">
          <div class="edu-period">${esc(item.period)}</div>
          <div class="edu-main${item.logo ? '' : ' edu-main--nologo'}">
            ${logoHTML}
            <div class="edu-copy">
              <h3 class="edu-degree">${heading}</h3>
              ${placeInner ? `<p class="edu-place">${placeInner}</p>` : ''}${advisorRows ? `
              <div class="edu-detail">
              ${advisorRows}
              </div>` : ''}
            </div>
          </div>
        </article>`;
  }).join('\n');
}

// Research — ported verbatim from js/research.js (affiliation is intentionally
// unused there, so it is omitted here too to keep the output identical).
function researchRichText(s) {
  return esc(s).replace(/&lt;u&gt;/g, '<u>').replace(/&lt;\/u&gt;/g, '</u>');
}
// Research rows reuse the Education row markup (.edu-item: period | logo |
// copy) so the two sections read identically. `logo` is a path in
// research.json (assets/logos/…); the box is the same 72px .edu-logo.
function researchLogoHTML(src, alt) {
  if (!src) return '';
  return `<div class="edu-logo"><img src="${esc(src)}" alt="${esc(alt)} logo" width="72" height="72" loading="lazy" decoding="async" /></div>`;
}
function researchRow({ period, logo, logoAlt, headline, place, detail }) {
  return `        <article class="edu-item research-item">
          <div class="edu-period">${esc(period || '')}</div>
          <div class="edu-main${logo ? '' : ' edu-main--nologo'}">
            ${researchLogoHTML(logo, logoAlt)}
            <div class="edu-copy">
              <h4 class="edu-degree">${headline}</h4>
              ${place ? `<p class="edu-place">${place}</p>` : ''}${detail ? `
              <div class="edu-detail">
              ${detail}
              </div>` : ''}
            </div>
          </div>
        </article>`;
}
// Graduate project: title is the headline, organization is the place line,
// the summary bullets sit in the detail block. Project codes and keyword tags
// stay in research.json (llms-full.txt still lists the keywords) but are not
// shown on the page.
function researchProjectRow(p) {
  const summary = (p.summary || []).length
    ? `<ul class="research-summary">${p.summary.map(s => `<li>${researchRichText(s)}</li>`).join('')}</ul>`
    : '';
  return researchRow({
    period: p.period,
    logo: p.logo,
    logoAlt: p.org,
    headline: esc(p.title),
    place: `<strong>${esc(p.org)}</strong>`,
    detail: summary,
  });
}
// Undergraduate internship: lab is the headline, school + location make the
// place line, advisor + what was done go in the detail block (like advisors
// in Education).
function researchUndergradRow(g) {
  const advisor = g.advisor ? `<div><span class="adv-label">Advisor:</span> ${esc(g.advisor)}</div>` : '';
  const items = (g.items || []).length
    ? `<ul class="research-summary">${g.items.map(it => `<li>${researchRichText(it)}</li>`).join('')}</ul>`
    : '';
  const loc = g.location ? `<span class="edu-loc">${PIN_SVG}${esc(g.location)}</span>` : '';
  return researchRow({
    period: g.period,
    logo: g.logo,
    logoAlt: g.institution || g.lab,
    headline: esc(g.lab),
    place: `${g.institution ? `<strong>${esc(g.institution)}</strong>` : ''}${loc}`,
    detail: advisor + items,
  });
}
function researchSectionHTML(section) {
  const title = `<h3 class="research-section__title">${esc(section.title)}</h3>`;
  const rows = section.type === 'graduate'
    ? (section.projects || []).map(researchProjectRow)
    : section.type === 'undergraduate'
      ? (section.groups || []).map(researchUndergradRow)
      : [];
  if (!rows.length) return '';
  return `
          <section class="research-section">
            ${title}
            <div class="edu-list">
${rows.join('\n')}
            </div>
          </section>`;
}
function renderResearch() {
  const data = readJSON('research.json');
  return ((data && data.sections) || []).map(researchSectionHTML).join('');
}

// News (home): `date · KIND label · body · tag`. Items past the first 5 get a
// --extra class so CSS hides them until the "Show more" toggle.
//   • `kind` (award / grant / paper / project / scholarship) becomes the small
//     uppercase label; when the CMS leaves it empty it is guessed from the text.
//   • `{{TMTT}}` / `{{WPTCE 2026}}` in the body become the same highlighter
//     marks (same color per venue) as on the Publications list.
function newsKind(n) {
  if (n.kind) return String(n.kind);
  const t = String(n.body || '').toLowerCase();
  if (/scholarship|fellowship/.test(t)) return 'scholarship';
  if (/grant/.test(t)) return 'grant';
  if (/award|prize|winner/.test(t)) return 'award';
  if (/accepted|published|journal|paper/.test(t)) return 'paper';
  if (/project|joined/.test(t)) return 'project';
  return 'news';
}
function newsBodyHTML(body) {
  return String(body || '').replace(/\{\{(.+?)\}\}/g, (_, token) => {
    const name = venueFullName(token);
    const title = name ? ` title="${esc(name)}"` : '';
    return `<span class="venue-mark" style="--marker-color:${venueColorFor(token)}"${title}>${esc(token.trim())}</span>`;
  });
}
function renderNews() {
  const data = readJSON('news.json');
  const news = Array.isArray(data) ? data : (data?.news || []);
  const INITIAL = 5;
  return news.map((n, i) => {
    const tagClass = (n.tag === '1st Author' || n.tag === 'Project Lead') ? 'badge--tag' : 'badge--coauthor';
    const tag = n.tag ? ` <span class="badge ${tagClass}">${esc(n.tag)}</span>` : '';
    const kind = newsKind(n);
    const extra = i >= INITIAL ? ' news-item--extra' : '';
    return `        <li class="news-item${extra}" data-kind="${esc(kind)}">
          <span class="news-item__date">${esc(n.date)}</span>
          <span class="news-item__kind">${esc(kind)}</span>
          <span class="news-item__body">${newsBodyHTML(n.body)}${tag}</span>
        </li>`;
  }).join('\n');
}

// Press / media coverage (home). Renders the WHOLE section — heading included —
// so an empty press.json produces nothing at all rather than a bare heading.
function renderPress() {
  // Optional file — a missing press.json simply means "no coverage yet".
  const file = path.join(DATA_DIR, 'press.json');
  if (!fs.existsSync(file)) return '';
  const data = readJSON('press.json');
  const items = Array.isArray(data) ? data : (data?.press || []);
  if (!items.length) return '';
  const rows = items.map(p => {
    const outlet = p.outlet ? `<span class="press-item__outlet">${esc(p.outlet)}</span>` : '';
    const date = p.date ? `<span class="press-item__date">${esc(p.date)}</span>` : '';
    // The headline is the link; lang marks Korean vs English articles for screen readers.
    const langAttr = p.lang ? ` lang="${esc(p.lang)}"` : '';
    const title = p.url
      ? `<a class="press-item__title" href="${esc(p.url)}" target="_blank" rel="noopener"${langAttr}>${esc(p.title)}${ARROW_SVG}</a>`
      : `<span class="press-item__title"${langAttr}>${esc(p.title)}</span>`;
    return `        <li class="press-item">
          ${outlet}
          ${title}
          ${date}
        </li>`;
  }).join('\n');
  return `      <section aria-labelledby="press-heading">
      <h2 id="press-heading">In the News</h2>
      <ul class="press-list">
${rows}
      </ul>
    </section>`;
}

// Academic Service — two columns (Journal Reviewer | Teaching Assistant) from
// data/others.json. Plain <div>s inside (a nested <section> would pick up the
// global section margin).
function renderAcademicService() {
  const data = readJSON('others.json');
  const reviewer = (data.reviewer || []).map(it =>
    `<li><em>${esc(it.name)}</em>${it.year ? `, ${esc(it.year)}` : ''}.</li>`
  ).join('') || '<li class="loading">No entries yet.</li>';
  const ta = (data.ta || []).map(it => {
    const code = it.code ? ` (${esc(it.code)})` : '';
    const inst = it.institution ? `, ${esc(it.institution)}` : '';
    const term = it.term ? `, ${esc(it.term)}` : '';
    return `<li>${esc(it.course)}${code}${inst}${term}</li>`;
  }).join('') || '<li class="loading">No entries yet.</li>';
  return `<div class="service-grid">
        <div class="service-col">
          <h3 class="service-col__title" id="reviewer-heading">Journal Reviewer</h3>
          <ul class="others-list" id="list-reviewer">${reviewer}</ul>
        </div>
        <div class="service-col">
          <h3 class="service-col__title" id="ta-heading">Teaching Assistant</h3>
          <ul class="others-list" id="list-ta">${ta}</ul>
        </div>
      </div>`;
}

// Coursework — one column per school, side by side.
function renderCoursework() {
  const data = readJSON('others.json');
  const groups = (data.coursework || []).map(g => `
        <div class="coursework-group">
          <h3 class="coursework-group__title">${esc(g.school)}</h3>
          <ul class="coursework-list">${(g.courses || []).map(c => {
            if (typeof c === 'string') return `<li>${esc(c)}</li>`;
            const note = c.note ? ` <em class="coursework-note">(${esc(c.note)})</em>` : '';
            return `<li>${esc(c.name)}${note}</li>`;
          }).join('')}</ul>
        </div>`).join('');
  return `<div class="coursework-grid">${groups}
      </div>`;
}

// -- Publications (static-first) -----------------------------------------
// Ported from js/publications.js so the rendered markup is identical to what
// the browser used to produce. Differences are intentional and minimal:
//   • author highlight uses <span class="me"> (the browser's highlightAuthor),
//     NOT the <strong> used by the AI fallback above;
//   • each .pub-item carries data-first ("1" when it has the "1st Author" tag)
//     — CSS gives those an accent edge;
//   • every tab is rendered as a .tab-panel (all visible to no-JS crawlers;
//     CSS shows only the active one once JS is present).
function pubHasFirstAuthorTag(item) {
  return Array.isArray(item.tags) && item.tags.indexOf('1st Author') !== -1;
}

// Venue highlighter colors — one pastel "marker" per journal / conference
// SERIES, so every TMTT paper shares a color, every WPTCE paper another, etc.
// Keys are the acronym in the venue's parentheses ("(TMTT)", "(WPTCE 2025)")
// or, failing that, the venue text with years/seasons stripped. Venues not
// listed here get the next unused palette color (stable across builds because
// assignment follows the order of first appearance in publications.json).
const VENUE_COLORS = {
  'TMTT': '#FFE66D',       // yellow
  'TAP': '#B5F0B0',        // mint
  'AWPL': '#FFB8DE',       // pink
  'OJAP': '#BFC8FF',       // periwinkle
  'JEES': '#FFC48C',       // orange
  'WPTCE': '#A9E2FF',      // sky
  'IMS': '#DDB8FF',        // lavender
  'ISAP': '#DDF59A',       // lime
  'APMC': '#A5F0E6',       // aqua
  'URSI GASS': '#FFB3B3',  // coral
  'KIEES CONF.': '#E4E4E4' // neutral gray for the domestic series
};
const VENUE_PALETTE = ['#FFE66D', '#B5F0B0', '#FFB8DE', '#BFC8FF', '#FFC48C', '#A9E2FF',
  '#DDB8FF', '#DDF59A', '#A5F0E6', '#FFB3B3', '#E4E4E4', '#F5D0A9', '#C8E7D8', '#EAD1FF'];

function venueKey(venue) {
  const s = String(venue || '');
  const m = s.match(/\(([A-Za-z][A-Za-z/&.\- ]*?)\s*(?:19|20)?\d{0,4}\)/);
  if (m && m[1].trim()) return m[1].trim().toUpperCase();
  return s.replace(/\b(19|20)\d{2}\b/g, '')
    .replace(/\b(Winter|Summer|Autumn|Spring|Fall)\b/gi, '')
    .replace(/\s+/g, ' ').trim().toUpperCase();
}

let venueColorMap = null;
let venueNameMap = null;   // key → first full venue string seen (tooltips on news marks)
function buildVenueMaps() {
  venueColorMap = new Map();
  venueNameMap = new Map();
  const pubs = readJSON('publications.json');
  const all = [
    ...(pubs.international_journals?.under_review || []),
    ...(pubs.international_journals?.published || []),
    ...(pubs.international_conferences || []),
    ...(pubs.domestic_conferences || []),
  ];
  const used = new Set(Object.values(VENUE_COLORS));
  for (const p of all) {
    const key = venueKey(p.venue);
    if (!key || venueColorMap.has(key)) continue;
    let color = VENUE_COLORS[key];
    if (!color) {
      color = VENUE_PALETTE.find(c => !used.has(c)) || VENUE_PALETTE[venueColorMap.size % VENUE_PALETTE.length];
      used.add(color);
    }
    venueColorMap.set(key, color);
    venueNameMap.set(key, String(p.venue));
  }
}
function venueColorFor(venue) {
  if (!venueColorMap) buildVenueMaps();
  return venueColorMap.get(venueKey(venue)) || VENUE_COLORS[venueKey(venue)] || VENUE_PALETTE[0];
}
function venueFullName(venue) {
  if (!venueNameMap) buildVenueMaps();
  return venueNameMap.get(venueKey(venue)) || '';
}

// Only the short name gets the marker stroke: the trailing parenthetical
// ("(TMTT)", "(WPTCE 2026)", "(URSI GASS 2023)") or, for venues written
// without one ("2026 KIEES Winter Conf."), the society acronym.
function venueMarkHTML(venue) {
  if (!venue) return '';
  const s = String(venue);
  const color = venueColorFor(venue);
  const mark = t => `<span class="venue-mark" style="--marker-color:${color}">${esc(t)}</span>`;
  let inner;
  const paren = s.match(/\(([^()]+)\)\s*$/);
  if (paren) {
    inner = `${esc(s.slice(0, paren.index))}(${mark(paren[1])})${esc(s.slice(paren.index + paren[0].length))}`;
  } else {
    const acro = s.match(/\b[A-Z]{3,}\b/);
    inner = acro
      ? `${esc(s.slice(0, acro.index))}${mark(acro[0])}${esc(s.slice(acro.index + acro[0].length))}`
      : mark(s);
  }
  return `<span class="pub-item__venue" data-venue="${esc(venueKey(venue))}">${inner}</span>`;
}

// Mirror of main.js highlightAuthor: wrap the owner's name in <span class="me">.
function highlightAuthorMe(authors, me) {
  if (!authors) return '';
  const safe = esc(authors);
  if (!me) return safe;
  const safeMe = esc(me);
  const re = new RegExp(safeMe.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
  return safe.replace(re, () => `<span class="me">${safeMe}</span>`);
}

// Button row in a fixed order — Abstract, Keywords, BibTeX, DOI, PDF — plus the
// Abstract / Keywords panels that the first two buttons toggle. The panel text
// is in the static HTML regardless (hidden by CSS only once JS is present), so
// crawlers and no-JS readers see it; llms-full.txt and the JSON-LD carry it too.
let pubPanelSeq = 0;
function pubActionsHTML(p) {
  const notes = [];
  const buttons = [];
  const panels = [];
  (p.notes || []).forEach(n => {
    const kind = n && n.kind ? n.kind : 'info';
    const label = typeof n === 'string' ? n : (n && n.label) || '';
    const icon = (n && n.icon) ? n.icon : '';
    if (!label) return;
    const iconHTML = icon ? `<span class="pub-note__icon">${esc(icon)}</span>` : '';
    notes.push(`<span class="pub-note pub-note--${esc(kind)}">${iconHTML}${esc(label)}</span>`);
  });
  if (p.abstract && p.abstract.trim()) {
    const id = `pub-abstract-${++pubPanelSeq}`;
    buttons.push(`<button type="button" class="pub-btn pub-btn--abs" data-panel-toggle="${id}" aria-expanded="false" aria-controls="${id}">Abstract</button>`);
    panels.push(`<div class="pub-panel" id="${id}"><span class="pub-panel__label">Abstract</span><p>${esc(p.abstract)}</p></div>`);
  }
  if (Array.isArray(p.keywords) && p.keywords.length) {
    const id = `pub-keywords-${++pubPanelSeq}`;
    buttons.push(`<button type="button" class="pub-btn pub-btn--kw" data-panel-toggle="${id}" aria-expanded="false" aria-controls="${id}">Keywords</button>`);
    panels.push(`<div class="pub-panel" id="${id}"><span class="pub-panel__label">Keywords</span><p>${esc(p.keywords.join(', '))}</p></div>`);
  }
  if (p.bibtex && p.bibtex.length) {
    buttons.push(`<button type="button" class="pub-btn pub-btn--bib" data-bibtex="${esc(p.bibtex)}" aria-label="Copy BibTeX">BibTeX</button>`);
  }
  if (p.doi) {
    buttons.push(`<a class="pub-btn pub-btn--doi" href="${esc(p.doi)}" target="_blank" rel="noopener" aria-label="DOI link">DOI</a>`);
  }
  if (p.pdf) {
    buttons.push(`<a class="pub-btn pub-btn--pdf" href="${esc(p.pdf)}" target="_blank" rel="noopener" aria-label="Open PDF">PDF</a>`);
  }
  let rows = '';
  if (notes.length && buttons.length) {
    rows = `
        <div class="pub-item__actions pub-item__actions--notes">${notes.join('')}</div>
        <div class="pub-item__actions pub-item__actions--buttons">${buttons.join('')}</div>`;
  } else if (notes.length || buttons.length) {
    rows = `<div class="pub-item__actions">${notes.concat(buttons).join('')}</div>`;
  }
  return rows + panels.join('');
}

function pubItemHTML(p, opts) {
  opts = opts || {};
  const num = p.number != null ? `<div class="pub-item__num">[${p.number}]</div>` : `<div class="pub-item__num"></div>`;
  const authors = highlightAuthorMe(p.authors, p.highlight_author);
  const tagsHTML = (p.tags || []).map(t => `<span class="badge--tag badge">${esc(t)}</span>`).join('');
  const details = p.details ? `<span class="pub-item__details">${esc(p.details)}</span>` : '';
  const venue = venueMarkHTML(p.venue);
  const titleSuffix = opts.bareTitle ? '' : ',';
  const titleQuote = opts.bareTitle ? '' : '"';
  const venuePrefix = opts.bareTitle ? '' : 'in ';

  let metaHTML;
  if (opts.splitMeta) {
    metaHTML = `
          <div class="pub-item__meta">${venue}</div>
          ${details ? `<div class="pub-item__meta pub-item__meta--sub">${details}</div>` : ''}`;
  } else {
    metaHTML = `<div class="pub-item__meta">${venuePrefix}${venue}${details ? ', ' + details : ''}</div>`;
  }

  const sep = opts.withDividers ? '<hr class="pub-item__sep" aria-hidden="true" />' : '';
  const first = pubHasFirstAuthorTag(p) ? '1' : '0';
  return `
      <li class="pub-item" data-first="${first}">
        ${num}
        <div class="pub-item__body">
          <div class="pub-item__authors">${authors}${tagsHTML}</div>
          ${sep}
          <div class="pub-item__title">${titleQuote}${esc(p.title)}${titleSuffix}${titleQuote}</div>
          ${sep}
          ${metaHTML}
          ${pubActionsHTML(p)}
        </div>
      </li>
    `;
}

function pubJournalsHTML(DATA) {
  const j = DATA.international_journals || {};
  const ur = j.under_review || [];
  const pub = j.published || [];
  const opts = { bareTitle: true, withDividers: true };
  let html = '';
  if (ur.length) {
    html += `<div class="pub-group"><div class="pub-group__title">Under Review</div><ul class="pub-list">${ur.map(p => pubItemHTML(p, opts)).join('')}</ul></div>`;
  }
  if (pub.length) {
    html += `<div class="pub-group"><div class="pub-group__title">Published Journals</div><ul class="pub-list">${pub.map(p => pubItemHTML(p, opts)).join('')}</ul></div>`;
  }
  return html || `<p class="loading">No entries yet.</p>`;
}

function pubListHTML(items, title, opts) {
  const arr = items || [];
  if (!arr.length) return `<p class="loading">No entries yet.</p>`;
  // NB: title is a trusted literal — left un-escaped to match the browser
  // (e.g. the apostrophe in "Int'l Conferences" must stay literal).
  return `<div class="pub-group"><div class="pub-group__title">${title}</div><ul class="pub-list">${arr.map(p => pubItemHTML(p, opts)).join('')}</ul></div>`;
}

function pubPatentItemHTML(p) {
  const inv = highlightAuthorMe(p.inventors || '', p.highlight_author);
  const countryBadge = p.country ? `<span class="badge badge--country">${esc(p.country)}</span>` : '';
  return `
      <li class="patent-item">
        <div class="patent-item__title">[${p.number}] ${esc(p.title || '')} ${countryBadge}</div>
        <ul class="patent-item__meta">
          ${p.inventors ? `<li><span class="patent-label">Inventors:</span> ${inv}</li>` : ''}
          ${p.patent_no ? `<li><span class="patent-label">Patent No.:</span> ${esc(p.patent_no)}</li>` : ''}
          ${p.granted_date ? `<li><span class="patent-label">Granted date:</span> ${esc(p.granted_date)}</li>` : ''}
        </ul>
      </li>`;
}

function pubPatentsHTML(items) {
  const arr = items || [];
  if (!arr.length) return `<p class="loading">No entries yet.</p>`;
  return `
      <div class="pub-group">
        <div class="pub-group__title">Patents</div>
        <ul class="patent-list">${arr.map(pubPatentItemHTML).join('')}</ul>
      </div>`;
}

function pubAwardItemHTML(a) {
  // Two-line item: the award NAME leads (that is what a reader scans for),
  // with the venue and date on a quieter second line — same top/sub rhythm
  // as the home-page press cards.
  const title = a.title ? `<strong class="award-name">${esc(a.title)}</strong>` : '';
  const hl = a.highlight ? ` <em class="award-highlight">(${esc(a.highlight)})</em>` : '';
  // "Co-author" is a data-only marker (not shown as a badge). Every other
  // tag (e.g. "1st Author") still renders as a visible badge.
  const tags = (a.tags || []).filter(t => t !== 'Co-author')
    .map(t => `<span class="badge--tag badge">${esc(t)}</span>`).join('');
  const tagsHTML = tags ? ` ${tags}` : '';
  const venue = a.venue ? `<span class="award-venue">${esc(a.venue)}</span>` : '';
  const date = a.date ? `<span class="award-date">${esc(a.date)}</span>` : '';
  const sub = (venue || date) ? `
          <div class="award-item__sub">${venue}${date}</div>` : '';
  return `<li class="award-item">
          <div class="award-item__main">${title}${hl}${tagsHTML}</div>${sub}
        </li>`;
}

// Render the four publication tabs as panels. Journals is active; the rest are
// visible to no-JS clients and hidden by CSS (html[data-js] .tab-panel:not(.is-active))
// once JavaScript loads.
function renderPublicationsTabs() {
  const DATA = readJSON('publications.json');
  const panel = (tab, active, inner) =>
    `<div class="tab-panel${active ? ' is-active' : ''}" data-tab="${tab}">${inner}</div>`;
  return [
    panel('international_journals', true, pubJournalsHTML(DATA)),
    panel('international_conferences', false,
      pubListHTML(DATA.international_conferences, "Int'l Conferences", { bareTitle: true, splitMeta: true, withDividers: true })),
    panel('domestic_conferences', false,
      pubListHTML(DATA.domestic_conferences, 'Domestic Conferences (KIEES)', { bareTitle: true, withDividers: true })),
    panel('patents', false, pubPatentsHTML(DATA.patents)),
  ].join('\n      ');
}

// Awards & Honors (data/awards.json): one card per category, headed by an
// <h3> because the whole block sits under the page's "03 Awards & Honors" <h2>.
function renderAwards() {
  const groups = readJSON('awards.json').awards || [];
  if (!groups.length) return `<p class="loading">No entries yet.</p>`;
  return groups.map(group => {
    const items = group.items || [];
    if (!items.length) return '';
    return `<div class="award-group">
        <h3 class="award-group__title">${esc(group.category || '')}</h3>
        <ul class="award-list">${items.map(pubAwardItemHTML).join('')}</ul>
      </div>`;
  }).filter(Boolean).join('\n      ');
}

// Replace the inner content between <!-- R:key:START --> / <!-- R:key:END -->.
function injectRegion(html, key, content) {
  const s = `<!-- R:${key}:START -->`, e = `<!-- R:${key}:END -->`;
  const re = new RegExp(escRe(s) + '[\\s\\S]*?' + escRe(e));
  if (!re.test(html)) throw new Error(`region "${key}" markers not found`);
  return html.replace(re, `${s}\n${content}\n      ${e}`);
}

