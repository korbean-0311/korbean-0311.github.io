#!/usr/bin/env node
/**
 * build-prerender.mjs — Injects a static, crawler-readable copy of each page's
 * JSON-driven content directly into the HTML.
 *
 * WHY
 *   The site renders all content client-side from data/*.json. AI crawlers and
 *   search bots that do NOT execute JavaScript therefore see only empty
 *   "Loading…" shells on every sub-page. This script pre-renders the same
 *   content into a `<div data-ai-fallback>` block inside each page so non-JS
 *   clients get the full text.
 *
 * ZERO VISUAL CHANGE FOR HUMANS
 *   The inline <head> script on every page sets `data-js` on <html> before the
 *   first paint. The CSS rule `html[data-js] [data-ai-fallback]{display:none}`
 *   (in css/style.css) hides the fallback the instant JS is present — so a
 *   JS-enabled visitor never sees it (no flash). A non-JS crawler never sets
 *   `data-js`, so the fallback stays visible as ordinary HTML.
 *
 * IDEMPOTENT
 *   Content is written between the markers
 *     <!-- AI-FALLBACK:START ... --> ... <!-- AI-FALLBACK:END -->
 *   Re-running replaces whatever is between them. If the markers are absent the
 *   block is inserted just before </main>.
 *
 * Run locally:   node scripts/build-prerender.mjs
 * Run in CI:     .github/workflows/build-llms.yml
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'data');

const START = '<!-- AI-FALLBACK:START (auto-generated by scripts/build-prerender.mjs — do not edit by hand) -->';
const END = '<!-- AI-FALLBACK:END -->';
const JSONLD_START = '<!-- AI-JSONLD:START (auto-generated by scripts/build-prerender.mjs — do not edit by hand) -->';
const JSONLD_END = '<!-- AI-JSONLD:END -->';
